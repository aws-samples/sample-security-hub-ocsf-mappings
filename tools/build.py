"""Validate the mapping CSV files and generate the JSON and Markdown files for every source.

Usage:
  python3 tools/build.py              validate and regenerate all sources
  python3 tools/build.py --check      validate, and fail if any generated file is out of date
  python3 tools/build.py guardduty    limit to one source (combine with --check if needed)
"""
import csv
import json
import re
import sys
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAPPINGS = ROOT / "mappings"
SAMPLE_FINDINGS = ROOT / "sample" / "findings"

# One entry per source. Everything below this table is shared.
SOURCES = OrderedDict(
    [
        (
            "guardduty",
            {
                "directory": "guardduty",
                "csv": "guardduty-to-ocsf.csv",
                "json": "guardduty-to-ocsf.json",
                "column": "guardduty_field",
                "display": "GuardDuty",
                "title": "Amazon GuardDuty",
                "classes": [(2004, "Detection Finding")],
                "ocsf_version": "1.8.0",
                "aws_extension_version": "1.1.0",
            },
        ),
        (
            "security-hub-cspm",
            {
                "directory": "security-hub-cspm",
                "csv": "asff-to-ocsf.csv",
                "json": "asff-to-ocsf.json",
                "column": "asff_field",
                "display": "Security Hub CSPM (ASFF)",
                "title": "AWS Security Hub CSPM (ASFF)",
                "classes": [(2003, "Compliance Finding")],
                "ocsf_version": "1.8.0",
                "aws_extension_version": "1.1.0",
            },
        ),
        (
            "inspector",
            {
                "directory": "inspector",
                "csv": "inspector-to-ocsf.csv",
                "json": "inspector-to-ocsf.json",
                "column": "inspector_field",
                "display": "Inspector",
                "title": "Amazon Inspector",
                "classes": [(2002, "Vulnerability Finding"), (2004, "Detection Finding")],
                "ocsf_version": "1.9.0",
                "aws_extension_version": "1.2.0",
            },
        ),
    ]
)

TRANSFORMS = {"direct", "converted"}

MAX_SAMPLE_BYTES = 15 * 1024
MAX_SAMPLES_PER_SOURCE = 3

ALLOWED_ACCOUNT_IDS = {"123456789012", "111122223333"}

# Text that must never appear in a mapping cell.
CONFIDENTIAL_PATTERNS = [
    (r"(?<!docs\.aws\.)(?<!\baws\.)\bamazon\.com\b", re.IGNORECASE),
    (r"@amazon\.com", re.IGNORECASE),
    (r"\b[VP]\d{9,}\b", 0),
    (r"\b[A-Z]{2,}-\d{3,}\b", 0),
    (r"\bCR-\d+\b", 0),
    (r"\binternal\b", re.IGNORECASE),
    (r"\btransformer\b", re.IGNORECASE),
    (r"\btodo\b", re.IGNORECASE),
    (r"\btbd\b", re.IGNORECASE),
    (r"\bfixme\b", re.IGNORECASE),
    (r"\bpending\b", re.IGNORECASE),
    (r"\bnot yet\b", re.IGNORECASE),
    (r"\bupcoming\b", re.IGNORECASE),
    (r"\bfuture\b", re.IGNORECASE),
    (r"\blaunch\b", re.IGNORECASE),
    (r"\bbeta\b", re.IGNORECASE),
    (r"\bpreview\b", re.IGNORECASE),
    (r"\bprod\b", re.IGNORECASE),
    (r"\bconfidential\b", re.IGNORECASE),
    (r"\bdo not share\b", re.IGNORECASE),
]
CONFIDENTIAL_RE = [re.compile(pattern, flags) for pattern, flags in CONFIDENTIAL_PATTERNS]
TWELVE_DIGITS = re.compile(r"(?<!\d)\d{12}(?!\d)")


def confidential_matches(value):
    hits = [rx.pattern for rx in CONFIDENTIAL_RE if rx.search(value)]
    hits += [m for m in TWELVE_DIGITS.findall(value) if m not in ALLOWED_ACCOUNT_IDS]
    return hits


GENERATED_NOTE = "Generated from the CSV files in this directory by `tools/build.py`. Do not edit this file by hand."


class BuildError(Exception):
    pass


def columns(source):
    return ["area", source["column"], "ocsf_field", "ocsf_type", "transform"]


def check_encoding(path):
    """CSV files are UTF-8 without a byte order mark, use \\n line endings and end with a newline."""
    raw = path.read_bytes()
    errors = []
    if raw.startswith(b"\xef\xbb\xbf"):
        errors.append(f"{path.relative_to(ROOT)}: starts with a byte order mark")
    try:
        raw.decode("utf-8")
    except UnicodeDecodeError as exc:
        errors.append(f"{path.relative_to(ROOT)}: not valid UTF-8 ({exc})")
    if b"\r" in raw:
        errors.append(f"{path.relative_to(ROOT)}: contains \\r; use \\n line endings")
    if raw and not raw.endswith(b"\n"):
        errors.append(f"{path.relative_to(ROOT)}: does not end with a newline")
    return errors



def read_rows(source):
    path = MAPPINGS / source["directory"] / source["csv"]
    rel = path.relative_to(ROOT)
    errors = check_encoding(path)
    if errors:
        raise BuildError("\n".join(errors))

    expected = columns(source)
    with path.open(newline="", encoding="utf-8") as fh:
        reader = csv.DictReader(fh)
        if reader.fieldnames != expected:
            raise BuildError(f"{rel}: expected columns {expected}, found {reader.fieldnames}")
        rows = [dict(row) for row in reader]

    seen = set()
    for n, row in enumerate(rows, start=2):
        if None in row or any(value is None for value in row.values()):
            errors.append(f"{rel}:{n}: wrong number of cells")
            continue
        if any(not row[c] for c in expected):
            errors.append(f"{rel}:{n}: every column is required")
        if any(value != value.strip() for value in row.values()):
            errors.append(f"{rel}:{n}: leading or trailing whitespace")
        if row["transform"] not in TRANSFORMS:
            errors.append(f"{rel}:{n}: unknown transform '{row['transform']}' (expected one of {sorted(TRANSFORMS)})")
        if ";" in row[source["column"]]:
            errors.append(f"{rel}:{n}: one source field per row; split rows that use several fields")
        key = (row["area"], row[source["column"]], row["ocsf_field"])
        if key in seen:
            errors.append(f"{rel}:{n}: duplicate row {key}")
        seen.add(key)
        for value in row.values():
            for hit in confidential_matches(value):
                errors.append(f"{rel}:{n}: confidential pattern {hit!r} in {value!r}")
    if errors:
        raise BuildError("\n".join(errors))
    return rows


def build_json(source, rows):
    document = OrderedDict()
    document["ocsf_version"] = source["ocsf_version"]
    document["aws_extension_version"] = source["aws_extension_version"]
    if len(source["classes"]) == 1:
        uid, name = source["classes"][0]
        document["class_uid"] = uid
        document["class_name"] = name
    else:
        document["classes"] = [OrderedDict([("class_uid", uid), ("class_name", name)]) for uid, name in source["classes"]]
    document["mappings"] = [OrderedDict((c, r[c]) for c in columns(source)) for r in rows]
    return json.dumps(document, indent=2, ensure_ascii=False) + "\n"


def anchor(text):
    return "".join(ch for ch in text.lower().replace(" ", "-") if ch.isalnum() or ch == "-")


def build_markdown(source, rows):
    classes = ", ".join(f"{name} (class_uid {uid})" for uid, name in source["classes"])
    out = [
        f"# {source['title']} to OCSF field mappings",
        "",
        f"{GENERATED_NOTE} Target: OCSF {source['ocsf_version']}, {classes}.",
        "",
    ]
    areas = OrderedDict()
    for row in rows:
        areas.setdefault(row["area"], []).append(row)

    out += ["## Contents", ""]
    out += [f"- [{area}](#{anchor(area)})" for area in areas]
    out.append("")

    heading = f"| {source['display']} field | OCSF field | OCSF type | Transform |"
    for area, area_rows in areas.items():
        out += [f"## {area}", "", heading, "| --- | --- | --- | --- |"]
        for row in area_rows:
            out.append(
                f"| `{row[source['column']]}` | `{row['ocsf_field']}` | {row['ocsf_type']} | {row['transform']} |"
            )
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def check_samples(names):
    errors = []
    for name in names:
        directory = SAMPLE_FINDINGS / SOURCES[name]["directory"]
        files = sorted(directory.glob("*.json")) if directory.is_dir() else []
        if len(files) > MAX_SAMPLES_PER_SOURCE:
            errors.append(f"{directory.relative_to(ROOT)}: {len(files)} files; at most {MAX_SAMPLES_PER_SOURCE} allowed")
        for path in files:
            rel = path.relative_to(ROOT)
            size = path.stat().st_size
            if size > MAX_SAMPLE_BYTES:
                errors.append(f"{rel}: {size} bytes; at most {MAX_SAMPLE_BYTES} allowed")
            try:
                json.loads(path.read_text(encoding="utf-8"))
            except (ValueError, UnicodeDecodeError) as exc:
                errors.append(f"{rel}: not valid JSON ({exc})")
            for match in TWELVE_DIGITS.findall(path.read_text(encoding="utf-8", errors="replace")):
                if match not in ALLOWED_ACCOUNT_IDS:
                    errors.append(f"{rel}: 12-digit number {match} is not a placeholder account ID")
    return errors


def main(argv):
    check = "--check" in argv
    names = [a for a in argv if not a.startswith("--")]
    unknown = [n for n in names if n not in SOURCES]
    if unknown:
        print(f"error: unknown source {', '.join(unknown)}; expected one of {', '.join(SOURCES)}", file=sys.stderr)
        return 2
    names = names or list(SOURCES)

    stale = []
    summary = []
    try:
        for name in names:
            source = SOURCES[name]
            rows = read_rows(source)
            directory = MAPPINGS / source["directory"]
            outputs = {
                directory / source["json"]: build_json(source, rows),
                directory / "MAPPINGS.md": build_markdown(source, rows),
            }
            for path, text in outputs.items():
                current = path.read_text(encoding="utf-8") if path.exists() else None
                if current != text:
                    stale.append(str(path.relative_to(ROOT)))
                    if not check:
                        path.write_text(text, encoding="utf-8")
            summary.append(f"{name}: {len(rows)} mappings")
        sample_errors = check_samples(names)
        if sample_errors:
            raise BuildError("\n".join(sample_errors))
    except BuildError as exc:
        for line in str(exc).splitlines():
            print(f"error: {line}", file=sys.stderr)
        return 1

    if check and stale:
        print(f"error: generated files are out of date: {', '.join(stale)}. Run python3 tools/build.py", file=sys.stderr)
        return 1
    print("ok: " + "; ".join(summary))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
